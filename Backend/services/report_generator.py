"""
report_generator.py
-------------------
Builds a PDF report for a CV session using fpdf2 (pure Python, no system binary needed).
"""

import re
from fpdf import FPDF
from datetime import datetime


def _safe(text: str) -> str:
    """Replace Unicode characters that latin-1 Helvetica can't encode."""
    return (
        text
        .replace("—", "-").replace("–", "-")
        .replace("‘", "'").replace("’", "'")
        .replace("“", '"').replace("”", '"')
        .replace("•", "-").replace("…", "...")
        .replace("â", "'")
        .encode("latin-1", errors="replace").decode("latin-1")
    )


def _parse_analysis(text: str) -> tuple[list[dict], list[str]]:
    """
    Parse LLM analysis into structured skill gaps and interview questions.

    Expected format:
        ## Skill Gaps
        1. **SkillName** - reason text
           - How to learn: suggestion

        ## Interview Questions
        1. Question text
    """
    skill_gaps: list[dict] = []
    questions: list[str] = []

    lower = text.lower()
    gap_start = lower.find("skill gap")
    q_start   = lower.find("interview question")

    # --- Skill gaps section ---
    if gap_start != -1:
        end = q_start if q_start != -1 else len(text)
        gap_block = text[gap_start:end]
        # Match numbered items: "1. **Skill** - reason"
        entries = re.split(r'\n(?=\d+[\.\)])', gap_block)
        for entry in entries:
            entry = entry.strip()
            if not entry or not re.match(r'\d+[\.\)]', entry):
                continue
            # Remove leading number
            body = re.sub(r'^\d+[\.\)]\s*', '', entry)
            # Extract skill name from **bold**
            skill_match = re.match(r'\*\*([^*]+)\*\*\s*[-—]?\s*(.*)', body, re.DOTALL)
            if skill_match:
                skill_name = skill_match.group(1).strip()
                rest = skill_match.group(2).strip()
            else:
                # fallback: first line is skill name
                lines = body.split('\n', 1)
                skill_name = lines[0].strip().lstrip('*').strip()
                rest = lines[1].strip() if len(lines) > 1 else ''

            # Split rest into reason and how-to-learn
            reason = ''
            how_to = ''
            for line in rest.split('\n'):
                line = line.strip().lstrip('-').strip()
                if line.lower().startswith('how to learn'):
                    how_to = re.sub(r'(?i)how to learn[:\s]*', '', line).strip()
                elif line:
                    reason = (reason + ' ' + line).strip()

            if skill_name:
                skill_gaps.append({
                    'name': skill_name,
                    'reason': reason,
                    'how_to': how_to,
                })

    # --- Interview questions section ---
    if q_start != -1:
        q_block = text[q_start:]
        for line in q_block.split('\n'):
            line = line.strip()
            if re.match(r'^\d+[\.\)]', line) and len(line) > 10:
                q = re.sub(r'^\d+[\.\)]\s*', '', line).strip()
                if q:
                    questions.append(q)

    return skill_gaps, questions


class _HireIQReport(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(109, 40, 217)
        self.cell(0, 10, "HireIQ - CV Analysis Report", align="C")
        self.ln(4)
        self.set_draw_color(109, 40, 217)
        self.set_line_width(0.5)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(
            0, 10,
            f"Page {self.page_no()} - Generated by HireIQ on {datetime.utcnow().strftime('%Y-%m-%d')}",
            align="C",
        )

    def section_title(self, title: str):
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(109, 40, 217)
        self.ln(5)
        self.cell(0, 8, _safe(title), ln=True)
        self.set_draw_color(220, 210, 250)
        self.set_line_width(0.3)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(4)
        self.set_text_color(30, 30, 30)

    def score_badge(self, score: float):
        color = (34, 197, 94) if score >= 70 else (245, 158, 11) if score >= 40 else (239, 68, 68)
        self.set_font("Helvetica", "B", 32)
        self.set_text_color(*color)
        self.cell(0, 16, f"{score:.1f}%", align="C", ln=True)
        self.set_font("Helvetica", size=10)
        self.set_text_color(120, 120, 120)
        self.cell(0, 6, "Match Score", align="C", ln=True)
        self.ln(4)
        self.set_text_color(30, 30, 30)

    def score_bar(self, label: str, value: float, max_value: float = 10):
        bar_width = 110
        filled = int((value / max_value) * bar_width)
        y = self.get_y()
        self.set_font("Helvetica", size=9)
        self.set_text_color(60, 60, 60)
        self.cell(42, 6, label)
        bar_x = self.get_x()
        self.set_fill_color(235, 228, 255)
        self.rect(bar_x, y + 1, bar_width, 4, style="F")
        self.set_fill_color(109, 40, 217)
        if filled > 0:
            self.rect(bar_x, y + 1, filled, 4, style="F")
        self.set_xy(bar_x + bar_width + 4, y)
        self.cell(20, 6, f"{value:.1f}/10", ln=True)
        self.ln(1)

    def skill_pills(self, skills: list[str]):
        """Render skills as pill-like tags, wrapping across rows."""
        self.set_font("Helvetica", size=9)
        pill_h = 6
        pill_pad_x = 4
        pill_pad_y = 1
        gap = 3
        margin_left = 10
        page_right = 200
        x = margin_left
        y = self.get_y()

        for skill in skills:
            label = _safe(skill)
            w = self.get_string_width(label) + pill_pad_x * 2
            if x + w > page_right:
                x = margin_left
                y += pill_h + gap
                self.set_y(y)

            # Pill background
            self.set_fill_color(237, 233, 254)
            self.set_draw_color(196, 181, 253)
            self.set_line_width(0.2)
            self.rect(x, y, w, pill_h + pill_pad_y * 2, style="DF")

            # Pill text
            self.set_text_color(88, 28, 135)
            self.set_xy(x, y + pill_pad_y)
            self.cell(w, pill_h, label, align="C")
            x += w + gap

        self.ln(pill_h + gap + 4)

    def skill_gap_card(self, index: int, name: str, reason: str, how_to: str):
        """Render a single skill gap as a styled card."""
        # Card background
        card_x = 10
        card_w = 190
        start_y = self.get_y()

        # Estimate height: name=7, reason lines ~5 each, how_to lines ~5 each
        reason_lines = max(1, len(reason) // 80 + 1) if reason else 0
        howto_lines  = max(1, len(how_to) // 80 + 1) if how_to else 0
        card_h = 8 + (reason_lines * 5 if reason else 0) + (howto_lines * 5 + 5 if how_to else 0) + 6

        # Check page break
        if start_y + card_h > self.h - self.b_margin:
            self.add_page()
            start_y = self.get_y()

        self.set_fill_color(250, 248, 255)
        self.set_draw_color(220, 210, 250)
        self.set_line_width(0.3)
        self.rect(card_x, start_y, card_w, card_h, style="DF")

        # Left accent bar
        self.set_fill_color(109, 40, 217)
        self.rect(card_x, start_y, 3, card_h, style="F")

        # Index badge
        self.set_xy(card_x + 6, start_y + 2)
        self.set_font("Helvetica", "B", 8)
        self.set_text_color(109, 40, 217)
        self.cell(8, 5, str(index), align="C")

        # Skill name
        self.set_xy(card_x + 16, start_y + 2)
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(30, 20, 60)
        self.cell(0, 5, _safe(name), ln=True)

        # Reason
        if reason:
            self.set_x(card_x + 16)
            self.set_font("Helvetica", size=9)
            self.set_text_color(70, 70, 70)
            self.multi_cell(card_w - 20, 5, _safe(reason))

        # How to learn
        if how_to:
            self.set_x(card_x + 16)
            self.set_font("Helvetica", "I", 8)
            self.set_text_color(100, 80, 170)
            self.multi_cell(card_w - 20, 5, _safe(f"How to learn: {how_to}"))

        # Pad to end of card
        self.set_y(start_y + card_h + 3)

    def question_row(self, index: int, text: str):
        """Render a numbered interview question row."""
        y = self.get_y()
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(109, 40, 217)
        self.set_x(10)
        self.cell(8, 7, f"{index}.", align="R")
        self.set_font("Helvetica", size=9)
        self.set_text_color(40, 40, 40)
        self.set_x(20)
        self.multi_cell(175, 5, _safe(text))
        self.ln(2)


def generate_report(
    cv_filename: str,
    match_score: float,
    skills: list[str],
    analysis_text: str,
    interview_results: list[dict],
) -> bytes:
    skill_gaps, questions = _parse_analysis(analysis_text)

    pdf = _HireIQReport()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # ── Meta ──────────────────────────────────────────────────────────────────
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(140, 140, 140)
    pdf.cell(
        0, 6,
        _safe(f"CV: {cv_filename}    |    Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M')} UTC"),
        ln=True,
    )
    pdf.ln(2)

    # ── Match Score ────────────────────────────────────────────────────────────
    pdf.section_title("Match Score")
    pdf.score_badge(match_score)

    # Score interpretation
    if match_score >= 70:
        interpretation = "Strong match - this candidate aligns well with the job requirements."
    elif match_score >= 40:
        interpretation = "Moderate match - some gaps exist but the candidate shows potential."
    else:
        interpretation = "Weak match - significant skill gaps relative to the job description."
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(100, 100, 100)
    pdf.cell(0, 6, _safe(interpretation), align="C", ln=True)
    pdf.ln(3)

    # ── Skills Detected ────────────────────────────────────────────────────────
    if skills:
        pdf.section_title(f"Skills Detected in CV  ({len(skills)} found)")
        pdf.skill_pills(skills)

    # ── Skill Gap Analysis ─────────────────────────────────────────────────────
    if skill_gaps:
        pdf.section_title(f"Skill Gap Analysis  ({len(skill_gaps)} gaps identified)")
        for i, gap in enumerate(skill_gaps, 1):
            pdf.skill_gap_card(
                index=i,
                name=gap['name'],
                reason=gap['reason'],
                how_to=gap['how_to'],
            )
    elif analysis_text:
        # Fallback: raw text if parsing yielded nothing
        pdf.section_title("Skill Gap Analysis")
        clean = re.sub(r'\*\*|##?\s', '', analysis_text)
        pdf.set_font("Helvetica", size=9)
        pdf.set_text_color(60, 60, 60)
        pdf.multi_cell(0, 5, _safe(clean))
        pdf.ln(2)

    # ── Interview Questions ────────────────────────────────────────────────────
    if questions:
        pdf.section_title(f"Recommended Interview Questions  ({len(questions)} questions)")
        for i, q in enumerate(questions, 1):
            pdf.question_row(i, q)
        pdf.ln(2)

    # ── Interview Results ──────────────────────────────────────────────────────
    if interview_results:
        pdf.section_title(f"Recorded Interview Results  ({len(interview_results)} answers)")
        for i, r in enumerate(interview_results, 1):
            # Question heading
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(50, 50, 50)
            pdf.set_x(10)
            pdf.multi_cell(0, 6, _safe(f"Q{i}: {r.get('question', '')}"))
            pdf.ln(1)

            # Transcript block
            if r.get("transcript"):
                pdf.set_fill_color(248, 246, 255)
                pdf.set_draw_color(220, 210, 250)
                pdf.set_line_width(0.2)
                tx = 13
                tw = 184
                # estimate height
                t_text = _safe(f'"{r["transcript"]}"')
                lines_est = max(1, len(t_text) // 70 + 1)
                th = lines_est * 5 + 6
                ty = pdf.get_y()
                if ty + th > pdf.h - pdf.b_margin:
                    pdf.add_page()
                    ty = pdf.get_y()
                pdf.rect(tx, ty, tw, th, style="DF")
                pdf.set_font("Helvetica", "I", 9)
                pdf.set_text_color(80, 80, 80)
                pdf.set_xy(tx + 3, ty + 3)
                pdf.multi_cell(tw - 6, 5, t_text)
                pdf.ln(2)

            # Score bars
            pdf.score_bar("Clarity",   r.get("clarity_score")   or 0)
            pdf.score_bar("Relevance", r.get("relevance_score") or 0)
            pdf.score_bar("Depth",     r.get("depth_score")     or 0)

            ec = r.get("eye_contact_ratio")
            if ec is not None:
                ec_pct = int(ec * 100)
                ec_color = (34, 197, 94) if ec_pct >= 60 else (245, 158, 11) if ec_pct >= 30 else (239, 68, 68)
                pdf.set_font("Helvetica", size=9)
                pdf.set_text_color(*ec_color)
                pdf.cell(0, 6, f"Eye contact: {ec_pct}%", ln=True)

            # Divider between results
            pdf.ln(2)
            if i < len(interview_results):
                pdf.set_draw_color(240, 235, 255)
                pdf.set_line_width(0.2)
                pdf.line(10, pdf.get_y(), 200, pdf.get_y())
                pdf.ln(4)

    return bytes(pdf.output())
